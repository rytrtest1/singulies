import { createServer } from 'vite';
import { chromium } from 'playwright';
const OUT = process.argv[2], PORT = 5210;
const server = await createServer({ server: { port: PORT, strictPort: true, host: 'localhost' }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ headless: true, executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.setDefaultTimeout(90000);
const errs = []; page.on('pageerror', e => errs.push(String(e)));
await page.goto(`http://localhost:${PORT}/?envoi=0&seed=3&paiement=faux`);
await page.waitForTimeout(8000);
await page.mouse.click(195, 422); await page.keyboard.type('LEA', { delay: 140 }); await page.keyboard.press('Enter');
await page.waitForFunction(() => document.querySelector('#offre.bar-on'));
await page.waitForTimeout(9000);
await page.click('.of-bar .of-down');
await page.waitForTimeout(6000);
await page.screenshot({ path: `${OUT}/ex-0.png` });
const r = await page.evaluate(() => { const e = document.querySelector('.ex-slot.mid') || document.querySelectorAll('.ex-slot')[2]; const b = e.getBoundingClientRect(); return [b.left + b.width / 2, b.top + b.height / 2, document.querySelector('.of-up').className]; });
console.log('mid', r);
await page.mouse.click(r[0], r[1]);
await page.waitForTimeout(3000);
await page.screenshot({ path: `${OUT}/ex-1.png` });
for (const v of [-0.3, -0.6]) { await page.evaluate(v => window.__ex3.drag(v), v); await page.waitForTimeout(2500); await page.screenshot({ path: `${OUT}/ex-d${-v}.png` }); }
await page.evaluate(() => window.__ex3.drag(0)); await page.waitForTimeout(1500);
await page.mouse.move(300, 420); await page.mouse.down(); await page.mouse.move(80, 424, { steps: 2 }); await page.mouse.up();
await page.waitForTimeout(6000);
await page.screenshot({ path: `${OUT}/ex-3.png` });
console.log(errs);
await browser.close(); await server.close();
